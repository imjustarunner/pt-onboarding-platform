import express from 'express';
import {authenticate,requireActiveStatus} from '../middleware/auth.middleware.js';
import {excludeSupportClinicalContent} from '../middleware/supportContentAccess.middleware.js';
import {apiLimiter} from '../middleware/rateLimiter.middleware.js';
import * as handlers from '../controllers/narriva.controller.js';
import * as assessment from '../controllers/narrivaAssessmentEvidence.controller.js';
import {getClinicalSessionServiceCode,changeClinicalSessionServiceCode} from '../controllers/clinicalSessionServiceChange.controller.js';
const router=express.Router();
router.use(authenticate,requireActiveStatus,excludeSupportClinicalContent,apiLimiter);
router.get('/preferences',handlers.getNarrivaPreferences);
router.patch('/preferences',handlers.patchNarrivaPreferences);
router.post('/reviews',handlers.postNarrivaReview);
router.get('/reviews/:reviewId',handlers.getNarrivaReview);
router.patch('/reviews/:reviewId/findings',handlers.patchNarrivaFinding);
router.get('/notes/:noteId/status',handlers.getNarrivaNoteStatus);
router.get('/sessions/:sessionId/service',getClinicalSessionServiceCode);
router.post('/sessions/:sessionId/service',changeClinicalSessionServiceCode);
router.get('/assessments',assessment.listNarrivaAssessmentEvidence);
router.post('/assessments',assessment.preflightNarrivaAssessmentEvidence,assessment.receiveNarrivaAssessmentFile,assessment.preflightNarrivaAssessmentEvidence,assessment.uploadNarrivaAssessmentEvidence);
router.post('/assessments/:materialId/scan',assessment.rescanNarrivaAssessmentEvidence);
router.get('/assessments/:kind/:evidenceId/view',assessment.viewNarrivaAssessmentEvidence);
export default router;
