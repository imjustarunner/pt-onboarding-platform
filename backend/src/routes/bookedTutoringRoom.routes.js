import express from 'express';
import rateLimit from 'express-rate-limit';
import { authenticate, requireActiveStatus } from '../middleware/auth.middleware.js';
import * as room from '../services/bookedTutoringRoom.service.js';
import materials from './tutoringMaterials.routes.js';
const router=express.Router();
router.use(authenticate,requireActiveStatus);
const handle=fn=>async(req,res,next)=>{try{res.set('Cache-Control','no-store');const context=await room.bookedTutoringAccess(req,req.params.appointmentId);res.json(await fn(context,req));}catch(error){if(error.code==='UNRATED_LESSON_ACTIVITY')return res.status(409).json({error:{code:error.code,message:error.message}});next(error);}};
router.use('/:appointmentId/studio',async(req,res,next)=>{try{req.tutoringContext=await room.bookedTutoringAccess(req,req.params.appointmentId);next();}catch(e){next(e);}},materials);
router.get('/:appointmentId',handle(room.tutoringRoomStatus));
router.post('/:appointmentId/prepare',handle(room.prepareBookedTutoringHub));
router.post('/:appointmentId/start-in-person',handle(room.startBookedInPersonTutoring));
router.post('/:appointmentId/start-external',handle(room.startBookedExternalTutoring));
router.get('/:appointmentId/learning-context',handle(room.bookedTutoringLearningContext));
router.get('/:appointmentId/materials',handle(room.tutoringBoardMaterials));
router.get('/:appointmentId/join-link',handle(room.tutoringJoinLink));
router.post('/:appointmentId/invitation/revoke',handle(async(ctx,req)=>(await import('../services/tutoringGuest.service.js')).revokeTutoringInvitation(ctx,req.body.recipientUserId)));
router.get('/:appointmentId/lesson-record',handle(room.tutoringLessonRecord));
router.post('/:appointmentId/lesson-review',handle((ctx,req)=>room.tutoringLessonReview(ctx,req.body)));
router.post('/:appointmentId/board-draft',rateLimit({windowMs:60000,max:8,standardHeaders:true,legacyHeaders:false,keyGenerator:req=>String(req.user.id)}),handle((ctx,req)=>room.tutoringBoardDraft(ctx,req.body)));
router.post('/:appointmentId/join',handle(room.joinBookedTutoringRoom));
router.post('/:appointmentId/presence',handle(room.heartbeatBookedTutoringRoom));
router.post('/:appointmentId/token',handle(room.bookedTutoringToken));
router.post('/:appointmentId/admit/:visitId',handle((ctx,req)=>room.admitBookedTutoringParticipant(ctx,req.params.visitId)));
router.post('/:appointmentId/leave',handle(room.leaveBookedTutoringRoom));
router.post('/:appointmentId/end',handle(room.endBookedTutoringRoom));
router.get('/:appointmentId/learning-note-context',handle(room.bookedTutoringLearningContext));
router.get('/:appointmentId/note/pdf',async(req,res,next)=>{try{
 const ctx=await room.bookedTutoringAccess(req,req.params.appointmentId);
 const {note}=await room.bookedTutoringNote(ctx);
 if(!note) return res.status(404).json({error:{message:'Save the session record first.'}});
 const {tutoringSessionPdf}=await import('../services/tutoringSessionPdf.service.js');
 const result=await tutoringSessionPdf(req,note.session_id);
 res.set({'Content-Type':'application/pdf','Content-Disposition':`attachment; filename="${result.filename}"`,'Cache-Control':'no-store'}).send(result.bytes);
 }catch(error){next(error);}});
router.get('/:appointmentId/note',handle(ctx=>room.bookedTutoringNote(ctx)));
router.put('/:appointmentId/note',handle((ctx,req)=>room.bookedTutoringNote(ctx,req.body)));
router.get('/:appointmentId/workspace',handle((ctx,req)=>room.bookedTutoringWorkspace(ctx,'read',req.query)));
router.post('/:appointmentId/workspace',handle((ctx,req)=>room.bookedTutoringWorkspace(ctx,'append',req.body)));
router.post('/:appointmentId/workspace/download',handle((ctx,req)=>room.bookedTutoringWorkspace(ctx,'download',req.body)));
export default router;
