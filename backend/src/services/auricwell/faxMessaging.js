import { transaction, list, get, create, update, findSource, lockPractice, audit } from './repository.js';
import { fail, hash, uuid } from './policy.js';
import { normalizeSessionPhone } from './integrationPolicy.js';
import { platformIntegrations } from './platformIntegrations.js';
import { practiceMessagingContext } from './clientMessaging.js';
import { notifyreRequest } from './sessionTransports.js';
import { requireFaxSupport, faxRoute, faxPdf, normalizeFaxEvent, faxStatusUpdate } from './faxPolicy.js';

const carrierKey = id => `notifyre:${hash(id)}`;
export async function faxInbox(ctx) {
  requireFaxSupport(ctx);
  const { settings } = await platformIntegrations();
  let number = '', canSend = false;
  try { const route = faxRoute(settings, ctx.practiceId); number = route.mainNumber; canSend = !!route.faxEnabled; } catch { /* Existing faxes remain accessible. */ }
  return { number, canSend, records: await list(ctx, 'fax', { limit: 500 }) };
}
export async function sendFax(ctx, input, transport = notifyreRequest) {
  requireFaxSupport(ctx);
  if (!uuid(input.requestId)) throw fail(400, 'A unique send request is required.');
  const to = normalizeSessionPhone(input.to);
  if (!to) throw fail(400, 'Enter the recipient fax number including country code.');
  const pdf = await faxPdf(input.base64);
  const fingerprint = hash(`${to}:${pdf.base64}`);
  const job = await transaction(async db => {
    await lockPractice(ctx, db);
    const prior = await findSource(ctx, 'fax', `send:${input.requestId}`, db);
    if (prior) {
      if (prior.data.fingerprint !== fingerprint) throw fail(409, 'This send request already belongs to a different fax. Start a new fax.');
      return { record: prior, claimed: false };
    }
    const { settings } = await platformIntegrations(db);
    const route = faxRoute(settings, ctx.practiceId, true);
    if (to === route.mainNumber) throw fail(400, 'Choose a different recipient from your own primary number.');
    const doc = await create(ctx, 'fax_document', { base64: pdf.base64 }, {}, db);
    const record = await create(ctx, 'fax', { direction: 'sent', from: route.mainNumber, to, status: 'sending',
      documentId: doc.id, pages: pdf.pages, fingerprint, sentBy: ctx.accountId, attemptedAt: new Date().toISOString() },
      { sourceKey: `send:${input.requestId}` }, db);
    return { record, claimed: true, token: settings.notifyre.apiToken };
  });
  if (!job.claimed) return job.record;
  // Persist the claim BEFORE the carrier call. Never retry an ambiguous send automatically.
  let carrierId = null;
  try {
    const receipt = await transport(job.token, '/fax/send', { Faxes: {
      Recipients: [{ Type: 'fax_number', Value: to }], SendFrom: job.record.data.from,
      ClientReference: job.record.id, Subject: 'Fax', IsHighQuality: true,
      Documents: [{ Filename: 'fax.pdf', Data: pdf.base64 }],
    } });
    carrierId = String(receipt?.FaxID ?? receipt?.faxID ?? receipt?.faxId ?? '');
    if (!/^[a-zA-Z0-9_-]{1,150}$/.test(carrierId)) throw fail(503, 'Missing carrier receipt.');
  } catch { /* Carrier may have accepted the fax. Keep it for manual receipt reconciliation. */ }
  return transaction(async db => {
    const current = await get(ctx, 'fax', job.record.id, db, true);
    if (current.data.eventAt) return current; // A signed callback can beat the HTTP response.
    return update(ctx, current, { ...current.data, carrierId: carrierId || null,
      status: carrierId ? 'submitted' : 'needs_review' }, db);
  });
}
export async function acceptFaxEvent(settings, parsed) {
  const event = normalizeFaxEvent(parsed);
  const primary = event.direction === 'received' ? event.to : event.from;
  const route = settings.clientMessaging?.routes?.find(r => r.mainNumber === primary);
  if (!route) throw fail(409, 'This fax number has no primary agency route.');
  faxRoute(settings, route.practiceId);
  const ctx = await practiceMessagingContext(route.practiceId);
  requireFaxSupport(ctx);
  await transaction(async db => {
    await lockPractice(ctx, db);
    let record = await findSource(ctx, 'fax', carrierKey(event.carrierId), db);
    if (event.direction === 'sent' && uuid(event.reference)) {
      // Reference is generated by our app. Never fall back across practices.
      record = await get(ctx, 'fax', event.reference, db, true);
      if (record.data.direction !== 'sent' || record.data.to !== event.to || record.data.from !== event.from
        || (record.data.carrierId && record.data.carrierId !== event.carrierId)) throw fail(409, 'Fax receipt does not match the send request.');
    }
    if (record) {
      if (record.data.direction !== event.direction || record.data.to !== event.to || record.data.from !== event.from)
        throw fail(409, 'Fax receipt does not match the stored fax.');
      if (event.direction === 'sent') {
        const next = faxStatusUpdate(record.data, event);
        if (next !== record.data) await update(ctx, record, { ...next, carrierId: event.carrierId }, db);
      }
    } else {
      await create(ctx, 'fax', { ...event, eventAt: event.timestamp, reviewedAt: null }, { sourceKey: carrierKey(event.carrierId) }, db);
    }
  });
  return { accepted: true };
}
export async function downloadFax(ctx, id, transport = notifyreRequest) {
  requireFaxSupport(ctx);
  const record = await get(ctx, 'fax', id);
  let document;
  if (record.data.documentId) document = await get(ctx, 'fax_document', record.data.documentId);
  else {
    if (record.data.direction !== 'received') throw fail(409, 'This fax was sent outside the app. Retrieve its document in Notifyre.');
    const { settings } = await platformIntegrations();
    faxRoute(settings, ctx.practiceId);
    const result = await transport(settings.notifyre.apiToken, `/fax/received/${encodeURIComponent(record.data.carrierId)}/download`);
    const pdf = await faxPdf(result?.Base64Str ?? result?.base64Str);
    document = await transaction(async db => {
      const latest = await get(ctx, 'fax', id, db, true);
      if (latest.data.documentId) return get(ctx, 'fax_document', latest.data.documentId, db);
      const doc = await create(ctx, 'fax_document', { base64: pdf.base64 }, {}, db);
      await update(ctx, latest, { ...latest.data, documentId: doc.id, pages: pdf.pages }, db);
      return doc;
    });
  }
  await audit(ctx, 'fax.downloaded', id);
  return { base64: document.data.base64, filename: `fax-${id}.pdf` };
}
export async function reviewFax(ctx, id) {
  requireFaxSupport(ctx);
  return transaction(async db => {
    const record = await get(ctx, 'fax', id, db, true);
    return update(ctx, record, { ...record.data, reviewedAt: new Date().toISOString(), reviewedBy: ctx.accountId }, db);
  });
}
