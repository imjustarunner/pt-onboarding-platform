export function normalizeOutreachName(name) {
  return String(name || '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\b(elementary|middle|high|school|schools|academy|ms|hs|es|jr|junior|senior|prep|preparatory|charter|campus|international|community|k8|p8|pk)\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
