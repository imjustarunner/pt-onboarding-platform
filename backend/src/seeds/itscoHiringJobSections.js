export function buildPostingTextFromSections(batch, sections) {
  if (!sections) return '';
  const header = `${batch.title}\nLocation: ${batch.city}, ${batch.state}`;
  const resp = sections.responsibilities?.length
    ? `\n\nKey Responsibilities\n${sections.responsibilities.join('\n')}`
    : '';
  const qual = sections.qualifications?.length
    ? `\n\nQualifications\n${sections.qualifications.join('\n')}`
    : '';
  const ben = sections.benefits?.length
    ? `\n\nCompensation & Benefits\n${sections.benefits.join('\n')}`
    : '';
  return `${header}\n\n${sections.aboutTheRole || ''}${resp}${qual}${ben}`.trim();
}

