-- Staff-issued, recipient-bound office enrollment; provider and booking data stay server-side.
CREATE TABLE IF NOT EXISTS care_invitations (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 request_key VARCHAR(64) NOT NULL,
 agency_id INT NOT NULL,
 intake_link_id INT NOT NULL,
 provider_user_id INT NOT NULL,
 created_by_user_id INT NOT NULL,
 recipient_email VARCHAR(255) NOT NULL,
 modality ENUM('IN_PERSON','VIRTUAL') NOT NULL,
 office_location_id INT NULL,
 standing_assignment_id INT NULL,
 start_at DATETIME NULL,
 time_zone VARCHAR(100) NOT NULL DEFAULT 'America/Denver',
 occurrence_count INT NOT NULL DEFAULT 26,
 frequency VARCHAR(32) NOT NULL DEFAULT 'BIWEEKLY',
 service_code VARCHAR(32) NOT NULL DEFAULT '90837',
 status VARCHAR(32) NOT NULL DEFAULT 'draft',
 submission_id INT NULL,
 client_id INT NULL,
 booking_plan_id INT NULL,
 communication_id INT NULL,
 notified_status VARCHAR(32) NULL,
 last_error VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY care_invitation_request (created_by_user_id, request_key),
 UNIQUE KEY care_invitation_link (intake_link_id),
 KEY care_invitation_work (status, id),
 KEY care_invitation_client (agency_id, client_id),
 CONSTRAINT care_invitation_agency FOREIGN KEY (agency_id) REFERENCES agencies(id),
 CONSTRAINT care_invitation_intake FOREIGN KEY (intake_link_id) REFERENCES intake_links(id),
 CONSTRAINT care_invitation_provider FOREIGN KEY (provider_user_id) REFERENCES users(id)
);
