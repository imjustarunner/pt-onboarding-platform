CREATE TABLE IF NOT EXISTS guardian_service_cancellations (
  id CHAR(36) NOT NULL PRIMARY KEY,
  agency_id INT NOT NULL,
  client_id INT NOT NULL,
  provider_user_id INT NOT NULL,
  actor_user_id INT NOT NULL,
  appointment_id INT UNSIGNED NOT NULL,
  scope VARCHAR(24) NOT NULL,
  service_kind VARCHAR(30) NOT NULL,
  series_kind VARCHAR(24) NULL,
  series_key VARCHAR(190) NULL,
  request_hash CHAR(64) NOT NULL,
  payload_encrypted LONGTEXT NOT NULL,
  review_json JSON NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'queued',
  completed_count INT NOT NULL DEFAULT 0,
  attempts INT NOT NULL DEFAULT 0,
  available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  error_message VARCHAR(500) NULL,
  lease_token CHAR(36) NULL,
  lease_until DATETIME NULL,
  confirmed_at DATETIME(3) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY ix_guardian_cancel_work (status, lease_until),
  KEY ix_guardian_cancel_service (client_id, agency_id, provider_user_id, service_kind),
  KEY ix_guardian_cancel_series (agency_id, client_id, series_kind, series_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
