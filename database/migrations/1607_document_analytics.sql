-- Forward-only reading analytics. Does not change payroll or training completion.
CREATE TABLE IF NOT EXISTS document_reading_sessions (
  id CHAR(36) NOT NULL PRIMARY KEY,
  agency_id INT NOT NULL,
  user_id INT NOT NULL,
  document_key VARCHAR(100) NOT NULL,
  document_title VARCHAR(250) NOT NULL,
  version_id INT NULL,
  surface VARCHAR(30) NOT NULL,
  device_class VARCHAR(12) NOT NULL,
  coverage VARCHAR(20) NOT NULL,
  section_slug VARCHAR(160) NOT NULL DEFAULT '',
  opened_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  seen_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  credited_through_at DATETIME(3) NULL,
  sequence_number INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 0,
  active_seconds INT NOT NULL DEFAULT 0,
  KEY idx_document_sessions_scope (agency_id, document_key, opened_at),
  KEY idx_document_sessions_user (user_id, seen_at),
  KEY idx_document_sessions_credited (user_id, credited_through_at),
  CONSTRAINT fk_document_sessions_agency FOREIGN KEY (agency_id) REFERENCES agencies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_document_sessions_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS document_reading_events (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  event_key VARCHAR(100) NOT NULL,
  agency_id INT NOT NULL,
  user_id INT NOT NULL,
  document_key VARCHAR(100) NOT NULL,
  document_title VARCHAR(250) NOT NULL,
  version_id INT NULL,
  session_id CHAR(36) NULL,
  surface VARCHAR(30) NOT NULL,
  event_type VARCHAR(20) NOT NULL,
  section_slug VARCHAR(160) NOT NULL DEFAULT '',
  label VARCHAR(250) NULL,
  target VARCHAR(300) NULL,
  question_text TEXT NULL,
  answer_status VARCHAR(30) NULL,
  active_seconds INT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_document_event (user_id, event_key),
  KEY idx_document_events_scope (agency_id, document_key, created_at),
  KEY idx_document_events_dates (agency_id, created_at),
  KEY idx_document_events_person (agency_id, user_id, created_at),
  CONSTRAINT fk_document_events_agency FOREIGN KEY (agency_id) REFERENCES agencies(id) ON DELETE RESTRICT,
  CONSTRAINT fk_document_events_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
