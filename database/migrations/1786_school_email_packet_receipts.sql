CREATE TABLE IF NOT EXISTS school_email_packet_receipts (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  agency_id INT NOT NULL,
  school_organization_id INT NOT NULL,
  ticket_id INT NOT NULL,
  source_message_id INT NOT NULL,
  attachment_id INT NOT NULL,
  sender_user_id INT NOT NULL,
  packet_key CHAR(64) NOT NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'pending',
  referral_draft_id INT NULL,
  phi_document_id INT NULL,
  client_id INT NULL,
  processing_task_id INT NULL,
  ack_status VARCHAR(24) NOT NULL DEFAULT 'pending',
  ack_ticket_message_id INT NULL,
  communication_id INT NULL,
  transport_message_id VARCHAR(255) NULL,
  error_code VARCHAR(100) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_school_email_packet_content (agency_id,packet_key),
  UNIQUE KEY uq_school_email_packet_source (agency_id,source_message_id,attachment_id),
  KEY idx_school_email_packet_ticket (agency_id,ticket_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
