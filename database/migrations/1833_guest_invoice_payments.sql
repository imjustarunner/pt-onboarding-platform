CREATE TABLE IF NOT EXISTS family_guest_invoices (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  agency_id INT NOT NULL,
  allocation_id BIGINT NOT NULL,
  issued_by_user_id INT NOT NULL,
  payer_user_id INT NOT NULL,
  issuer_kind ENUM('payer','staff') NOT NULL DEFAULT 'payer',
  responsible_party_revision INT NULL,
  token_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  amount_cents INT NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  locale VARCHAR(8) NOT NULL DEFAULT 'en',
  expires_at DATETIME NOT NULL,
  revoked_at DATETIME NULL,
  payment_id BIGINT NULL,
  recipient_encrypted LONGTEXT NULL,
  delivery_status ENUM('draft','sending','sent','held','unknown') NOT NULL DEFAULT 'draft',
  communication_id BIGINT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  sent_at DATETIME NULL,
  UNIQUE KEY uq_guest_invoice_token (token_hash),
  UNIQUE KEY uq_guest_invoice_payment (payment_id),
  KEY ix_guest_invoice_allocation (agency_id,allocation_id),
  KEY ix_guest_invoice_expiry (expires_at,revoked_at),
  FOREIGN KEY (allocation_id) REFERENCES family_receivable_allocations(id),
  FOREIGN KEY (payment_id) REFERENCES family_ledger_payments(id),
  CHECK (amount_cents > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
