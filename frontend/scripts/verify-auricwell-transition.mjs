import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { PDFDocument } from 'pdf-lib';

const target = process.env.AURICWELL_TRANSITION_PREVIEW_URL || 'http://127.0.0.1:5185/auricwell-transition-preview.html';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [], networkWrites = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  page.setDefaultTimeout(12000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) networkWrites.push(request.url()); });
  await page.goto(target, { waitUntil: 'networkidle' });
  await page.getByText('Sample preview · Fictional clients only', { exact: true }).waitFor();
  await page.locator('.aw-context select').first().selectOption('7101');
  await page.locator('.aw-caseload li button').filter({ hasText: 'Taylor Example' }).click();
  await page.getByLabel('Demographics paste', { exact: true }).fill('Legal Name: Taylor Example\nDate of Birth: 2014-03-08\nPhone: 555-010-0200\nAdditional Contacts\nName: Pat Example\nRelationship: Parent\nPhone: 555-010-0300\nEmail: pat@example.test');
  await page.getByRole('button', { name: 'Review demographics and contacts', exact: true }).click();
  await page.getByLabel(/I compared the selected demographics/).check();
  await page.getByRole('button', { name: 'Save reviewed demographics and contacts', exact: true }).click();
  await page.getByText('Demographics and contacts saved on this client’s existing chart.', { exact: true }).waitFor();
  let snapshot = await page.evaluate(() => window.__awTransitionPreview.snapshot());
  assert.equal(snapshot.clients.find(client => client.id === 7201).date_of_birth, '2014-03-08');
  assert.equal(snapshot.clients.find(client => client.id === 7201).client_type, 'school');
  assert.equal(snapshot.clients.length, 2);
  assert.equal(snapshot.contacts['7201'].length, 1);
  await page.getByLabel('Insurance paste', { exact: true }).fill('Primary Insurance: Sample Health\nMember ID: SAMPLE123\nSubscriber Name: Pat Example\nSubscriber DOB: 1980-05-06\nRelationship to Subscriber: Child');
  await page.getByRole('button', { name: 'Review insurance', exact: true }).click();
  await page.getByLabel(/I compared the client, subscriber/).check();
  await page.getByRole('button', { name: 'Save reviewed insurance for billing review', exact: true }).click();
  await page.getByText('Insurance saved for billing review. Source import does not verify coverage or submit claims.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Medical history PDF', exact: true }).click();
  const pdf = await PDFDocument.create(); for (let i = 0; i < 3; i++) pdf.addPage().drawText(`Fictional archive page ${i + 1}`);
  await page.locator('.aw-archive input[type=file]').setInputFiles({ name: 'fictional-history.pdf', mimeType: 'application/pdf', buffer: Buffer.from(await pdf.save()) });
  await page.getByLabel(/I checked that every page belongs/).check();
  await page.getByRole('button', { name: 'Save PDF history to this chart', exact: true }).click();
  await page.getByText('The archive and manifest are saved. Open or download every volume and check completeness.', { exact: true }).waitFor();
  snapshot = await page.evaluate(() => window.__awTransitionPreview.snapshot());
  assert.equal(snapshot.documents['7201'].length, 2);
  await page.getByRole('button', { name: '2. Weekly agenda', exact: true }).click();
  await page.locator('.aw-agenda-context input[type=date]').fill('2026-11-16');
  const selectors = page.locator('.aw-agenda-context select');
  await selectors.nth(0).selectOption('7501'); await selectors.nth(1).selectOption('7502'); await selectors.nth(2).selectOption('IN_PERSON');
  await page.getByLabel('Weekly agenda paste', { exact: true }).fill('Monday | 09:00 | 09:50 | Taylor Example');
  await page.getByRole('button', { name: 'Read pasted agenda', exact: true }).click();
  await page.getByLabel(/I reviewed the client identities/).check();
  await page.locator('.aw-create').click();
  await page.getByText('Scheduled 1 new appointments; kept 0 existing appointments.', { exact: true }).waitFor();
  await page.getByRole('button', { name: '3. School appointment connection', exact: true }).click();
  await page.getByLabel('School appointment transition date').fill('2026-11-16');
  await page.getByLabel(/I reviewed the provider, school/).check();
  await page.getByRole('button', { name: 'Save transition date', exact: true }).click();
  await page.getByLabel('Saved school slot').selectOption('7601');
  await page.getByLabel(/Appointment \d+ ·/).check();
  await page.getByLabel(/I verified that these appointments belong/).check();
  await page.getByRole('button', { name: 'Link reviewed appointments', exact: true }).click();
  await page.getByRole('button', { name: 'Change appointment time', exact: true }).click();
  await page.locator('.move input[type=time]').nth(0).fill('10:00'); await page.locator('.move input[type=time]').nth(1).fill('10:50');
  await page.getByRole('button', { name: 'Save actual appointment', exact: true }).click();
  await page.locator('.sessions').filter({ hasText: '10:00' }).waitFor();
  snapshot = await page.evaluate(() => window.__awTransitionPreview.snapshot());
  assert.equal(snapshot.appointments.length, 1); assert.equal(snapshot.appointments[0].startTime, '10:00'); assert.equal(snapshot.links.length, 1);
  await page.screenshot({ path: '/private/tmp/auricwell-transition-school-preview.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Mobile page must not overflow');
  await page.screenshot({ path: '/private/tmp/auricwell-transition-mobile-preview.png', fullPage: true });
  assert.deepEqual(networkWrites, [], 'Sample preview must not reach a real API'); assert.deepEqual(errors, []);
  console.log('Browser trial passed: existing school chart enrichment, contacts, insurance, PDF+manifest, agenda booking, linked school edit, mobile layout, zero real API requests.');
} catch (error) {
  console.error(error.message);
  console.error('Browser errors:', errors);
  throw error;
} finally { await browser.close(); }
