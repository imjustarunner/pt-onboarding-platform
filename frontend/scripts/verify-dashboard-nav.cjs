// Local-only visual checks with fictional data. No live API requests are allowed.
const { chromium } = require('playwright');
const fs = require('node:fs');
const origin = 'http://127.0.0.1:5185';
const artifacts = '/tmp/dashboard-nav-refinements';
fs.mkdirSync(artifacts, { recursive: true });
const agency = {id:2,name:'Example Practice',slug:'example',portal_url:'example',organization_type:'agency',is_active:1,feature_flags:{clinicalChartEnabled:true,schoolPortalsEnabled:true},color_palette:{primary:'#247252',secondary:'#183a37',accent:'#247252'}};
const user = {id:99999,role:'provider',status:'ACTIVE_EMPLOYEE',first_name:'Example',last_name:'Provider',has_provider_access:true,has_supervisor_privileges:true,has_clinical_supervision:true,created_at:'2026-10-01T00:00:00Z',capabilities:{canViewTraining:true,canSignDocuments:true,canViewClients:true,canViewLibrary:true},agencies:[agency]};
const work = Array.from({length:60},(_,i)=>({id:`work-${i}`,clientId:i+1,clientName:`Example Client ${i+1}`,agencyId:2,date:'2026-10-25',noteType:'progress',status:i%2?'in_progress':'not_started',docStatus:i%2?'in_progress':'not_started'}));
const notes = Array.from({length:100},(_,i)=>({id:i+1,client_name:`Example Client ${i+1}`,provider_name:'Example Clinician',agency_id:2,date_of_service:'2026-10-24',note_kind:'progress'}));
const assert = (value, message) => {if(!value) throw new Error(message);};
(async()=>{
  const browser = await chromium.launch({channel:'chrome',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    page.setDefaultTimeout(20000);
    const errors=[]; page.on('pageerror',error=>{errors.push(error.stack);console.error(error.stack);});
    await page.route('**/api/**',async route=>{
      const p=new URL(route.request().url()).pathname; let data={};
      if(p.includes('auth/me')) data={user,agencies:[agency]};
      else if(p==='/api/users/99999') data=user;
      else if(p.includes('session-lock-config')) data={session:{phase:'active',serverNow:Date.now(),lastActivityAt:Date.now(),lockAt:Date.now()+600000,expiresAt:Date.now()+1200000,activityVersion:1}};
      else if(p.includes('onboarding-checklist')) data={completionPercentage:100};
      else if(p.includes('platform-branding')) data={organization_name:'Example',primary_color:'#247252'};
      else if(p.includes('preferences')) data={};
      else if(p==='/api/agencies'||p.includes('/agencies')&&p.includes('/users/')) data=[agency];
      else if(p==='/api/agencies/2') data=agency;
      else if(p.includes('by-slug')||p.includes('portal')) data={agency,organization:agency,colorPalette:agency.color_palette,portalUrl:'example'};
      else if(p==='/api/clinical-notes/work-queue') data={items:work};
      else if(p==='/api/me/notes-to-sign') data={notes,isSupervisor:true};
      else if(p.includes('my-history-status')) data={hasClinicalSupervision:true};
      else if(p.includes('provider-clinical-focus')) data={groups:[],clinicalFocus:{}};
      else if(p.includes('schedule-summary')) data={scheduleEvents:[],supervisionSessions:[],officeEvents:[],busyBlocks:[{startAt:'2026-10-26T16:00:00Z',endAt:'2026-10-26T17:00:00Z',activityType:'session',title:'Private title must never render'}]};
      else if(p.includes('meeting-invitations')) data={prompts:[]};
      else if(p.includes('user-nav/shortcuts')) data={shortcuts:[{page:'note-aid',path:'/note-aid',visit_count:8},{page:'clinical-note-generator',path:'/admin/clinical-note-generator',visit_count:6}]};
      else if(p==='/api/library/resources'||p==='/api/library/folders') data=[];
      else if(p.includes('/staff/directory')) data={staff:[{id:88888,displayName:'Example Coworker',workEmail:'coworker@example.test'}]};
      else if(/modules|documents|payroll|training|progress|certificates|presence|people|threads|notifications|messages|tickets|tasks|agencies|icons|departments|categories|reviews|programs|users|company-events/.test(p)) data=[];
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)});
    });
    await page.goto(origin+'/login');
    await page.evaluate(({user,agency})=>{localStorage.setItem('user',JSON.stringify(user));localStorage.setItem('userAgencies',JSON.stringify([agency]));localStorage.setItem('currentAgency',JSON.stringify(agency));localStorage.setItem('dashboard.learning.v1:99999',JSON.stringify({firstSeen:Date.now(),understood:['edit-layout','customize','search','focus','work','collapse','notifications','schedule','submit','quicknav']}));},{user,agency});
    await page.evaluate(async()=>{const {dashboardLearningTips}=await import('/src/tutorial/dashboardLearningTips.js');localStorage.setItem('dashboard.learning.v1:99999',JSON.stringify({firstSeen:Date.now(),understood:dashboardLearningTips.map(t=>t.id)}));});

    const report={roles:[],errors,artifacts};
    const menu=page.getByRole('navigation',{name:'My Dashboard sections'});
    const trigger=page.locator('[data-testid="desktop-dashboard-menu-trigger"]');
    for (const role of ['provider','clinical_practice_assistant','provider_plus','admin','support','super_admin']) {
      await page.mouse.move(1400,900);
      user.role=role;
      await page.evaluate(user=>localStorage.setItem('user',JSON.stringify(user)),user);
      await page.goto(origin+'/example/dashboard');
      await trigger.waitFor({timeout:60000});
      await page.locator('[data-card-id="overview"]').waitFor({state:'attached'});
      await page.waitForTimeout(800);
      await trigger.hover();await page.waitForTimeout(150);
      assert(!await menu.count(),'Brief pointer pass does not open menu');
      await page.waitForTimeout(500);await menu.waitFor();
      assert(await menu.getByRole('button',{name:'My Schedule',exact:true}).count(),role+' sees sidebar sections');
      const color=await trigger.evaluate(el=>getComputedStyle(el).color);
      const labels=await menu.locator('.dashboard-nav-label').allTextContents();
      const sidebarLabels=await page.locator('[data-card-id][data-label]').evaluateAll(elements=>elements.map(el=>el.dataset.label));
      assert(JSON.stringify(labels)===JSON.stringify(sidebarLabels),role+' menu matches the sidebar labels and order');
      const bounds=await menu.boundingBox();
      assert(bounds.x>=0&&bounds.x+bounds.width<=1440&&bounds.y+bounds.height<=1000,'Menu fits viewport');
      await page.screenshot({path:`${artifacts}/${role}-menu.png`});
      await menu.getByRole('button',{name:'My Schedule',exact:true}).click();
      await page.locator('[data-testid="schedule-command-bar"]').waitFor();
      assert(!await menu.count(),'Selecting section closes menu');
      assert(!new URL(page.url()).searchParams.has('dashboardCard'),'Navigation handoff is removed');
      await page.mouse.move(1400,900);await page.waitForTimeout(350);
      await trigger.click();await menu.waitFor();
      await page.keyboard.press('Escape');assert(!await menu.count(),'Escape closes menu');
      assert(await trigger.evaluate(el=>el===document.activeElement),'Escape returns focus');
      report.roles.push({role,color,labels});
    }
    await page.mouse.move(1400,900);await page.waitForTimeout(350);
    await trigger.click();await menu.waitFor();
    await menu.getByRole('button',{name:/^Tools and Resources/}).click();
    await menu.getByRole('button',{name:'Expand Library',exact:true}).click();
    await menu.getByRole('button',{name:'My Files',exact:true}).click();
    await page.waitForURL('**/library?section=mine');
    await page.mouse.move(1400,900);await page.waitForTimeout(350);
    await trigger.click();await menu.waitFor();
    await menu.getByRole('button',{name:'My Account',exact:true}).click();
    await page.waitForURL(url=>url.searchParams.get('tab')==='my');
    assert(!new URL(page.url()).searchParams.has('dashboardCard'),'Cross-page selection resolves to real dashboard section');
    await page.mouse.move(1400,900);await page.waitForTimeout(350);
    await trigger.click();await menu.waitFor();
    await page.mouse.click(1400,900);assert(!await menu.count(),'Outside click closes menu');
    await page.goto(origin+'/example/library');await trigger.waitFor();
    await trigger.click();
    await page.waitForTimeout(1000);await page.screenshot({path:`${artifacts}/fresh-menu.png`});
    await menu.getByRole('button',{name:'My Schedule',exact:true}).waitFor();
    assert(new URL(page.url()).pathname.endsWith('/dashboard'),'A fresh non-dashboard page loads the sidebar on click');
    await page.keyboard.press('Escape');
    await page.mouse.move(1400,900);await page.waitForTimeout(350);
    await page.setViewportSize({width:1100,height:650});
    await trigger.hover();await page.waitForTimeout(600);await menu.waitFor();
    const small=await menu.boundingBox();
    assert(small.x>=0&&small.x+small.width<=1100&&small.y+small.height<=650,'Menu fits short desktop screen');
    await page.screenshot({path:`${artifacts}/short-desktop.png`});
    report.shortViewport=small;
    fs.writeFileSync(`${artifacts}/report.json`,JSON.stringify(report,null,2));
    assert(!errors.length,`Browser errors: ${errors.join('; ')}`);console.log(JSON.stringify(report,null,2));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
