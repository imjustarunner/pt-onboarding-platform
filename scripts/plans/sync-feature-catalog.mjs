// Keep standalone deployment bundles in sync without importing across app roots.
// Run after updating the approved selections and inventory; --check makes no edits.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../../', import.meta.url);
const read = path => JSON.parse(readFileSync(new URL(path, root), 'utf8'));
const approved = read('deliverables/approved-feature-tiers.json');
const inventory = read('deliverables/feature-tier-inventory.json');
const tiers = ['basic', 'premium', 'premium_plus'];
if (approved.sharedFeatureScope !== 'agency') throw new Error('Shared features must use agency plans.');
if (new Set(approved.features.map(f => f.key)).size !== inventory.length) throw new Error('Duplicate or missing feature choices.');
const features = inventory.map(item => {
  const choice = approved.features.find(f => f.key === item.key);
  if (!choice || ![...tiers, 'separate'].includes(choice.minimumTier)) throw new Error(`Missing tier: ${item.key}`);
  if (choice.minimumTier !== item.minimumTier || choice.feature !== item.feature) throw new Error(`Inventory differs: ${item.key}`);
  return {
    key: item.key, label: item.feature, description: item.description,
    category: item.category, minimumTier: choice.minimumTier,
    products: item.products === 'Platform + AuricWell' ? ['platform', 'auricwell'] : ['platform'],
    scope: ['private_office', 'multiple_office_guests'].includes(item.key) ? 'individual' : 'agency',
    ...(item.key === 'focusMusic' ? { aliasOf: 'focusPackage' } : {})
  };
});
const output = '// Generated by scripts/plans/sync-feature-catalog.mjs. Edit the approved inventory, then regenerate.\n'
  + `export const PLAN_TIERS = Object.freeze(${JSON.stringify(approved.plans.map((name, index) => ({ id: tiers[index], name })))});\n`
  + `export const PLAN_FEATURES = Object.freeze(${JSON.stringify(features, null, 2)}.map(feature => Object.freeze({ ...feature, products: Object.freeze(feature.products) })));\n`;
for (const path of ['backend/src/constants/productPlanCatalog.js', 'frontend/src/config/productPlanCatalog.js']) {
  const url = new URL(path, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== output) throw new Error(`Stale catalog: ${path}`);
  } else writeFileSync(url, output);
}
console.log(`Validated ${features.length} approved feature assignments.`);
